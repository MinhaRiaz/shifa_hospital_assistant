import os

from langchain_community.document_loaders import DirectoryLoader, TextLoader

from langchain_text_splitters import RecursiveCharacterTextSplitter

from langchain_huggingface import HuggingFaceEmbeddings

from langchain_community.vectorstores import FAISS



DATA_PATH = "hospital_knowledge_base"

DB_FAISS_PATH = "faiss_index"



def create_vector_db():

    print(f"Loading policy documents from '{DATA_PATH}'...")



    # 1. Load all text files recursively

    loader = DirectoryLoader(

        DATA_PATH,

        glob="**/*.txt",

        loader_cls=TextLoader

    )

    documents = loader.load()



    if not documents:

        print("❌ No documents found!")

        return



    # 2. Extract and attach metadata (department, file_name, full_path)

    for doc in documents:

        source_path = doc.metadata.get("source", "")

        # Normalize path separators

        norm_path = os.path.normpath(source_path)

        parts = norm_path.split(os.sep)



        # Extract folder name right under hospital_knowledge_base as Department

        if len(parts) >= 2:

            department = parts[-2]  # e.g., 'Nursing', 'Emergency', 'Pharmacy'

            file_name = parts[-1]   # e.g., 'nursing_shift_handoff.txt'

        else:

            department = "General"

            file_name = os.path.basename(source_path)



        # Update metadata dictionary

        doc.metadata["department"] = department

        doc.metadata["/content/hospital_knowledge_base/Department/hospital_knowledge_base_departments.csv"] = file_name



    print(f" Loaded {len(documents)} document(s). Enhancing metadata...")



    # 3. Split documents into chunks (metadata propagates to each chunk automatically)

    text_splitter = RecursiveCharacterTextSplitter(

        chunk_size=500,

        chunk_overlap=50

    )

    docs = text_splitter.split_documents(documents)

    print(f"Created {len(docs)} text chunks with metadata.")



    # 4. Generate embeddings

    print("Generating embeddings with HuggingFace (all-MiniLM-L6-v2)...")

    embeddings = HuggingFaceEmbeddings(

        model_name="sentence-transformers/all-MiniLM-L6-v2",

        model_kwargs={'device': 'cpu'}

    )



    # 5. Save FAISS index (index.faiss + index.pkl contain embeddings, text, and metadata)

    print("Building FAISS index...")

    db = FAISS.from_documents(docs, embeddings)

    db.save_local(DB_FAISS_PATH)

    print(f"🎉 FAISS index and metadata successfully saved to '{DB_FAISS_PATH}'.")



if __name__ == "__main__":

    create_vector_db()



